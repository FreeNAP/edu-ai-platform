def lesson_content(course_idx: int, course_title: str, chapter_theme: str,
                   chapter_idx: int, lesson_tpl: str) -> str:
    """生成 2~4 段课时讲解，段落之间用空行分隔。"""
    kws = COURSE_KEYWORDS[course_idx % len(COURSE_KEYWORDS)]
    kw = kws[chapter_idx % len(kws)]
    other = kws[(chapter_idx + 1) % len(kws)]
    paras = _TEMPLATES.get(lesson_tpl, _TEMPLATES["核心概念精讲"])
    values = {
        "course": course_title,
        "chapter": chapter_theme,
        "kw": kw,
        "other": other,
        "kws": "、".join(kws),
    }
    return "\n\n".join(p.format(**values) for p in paras)
